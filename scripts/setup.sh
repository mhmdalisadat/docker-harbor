#!/usr/bin/env bash
# Usage: setup.sh [--force]
# Validate .env, generate missing secrets once, render harbor.yml, run the official Harbor
# `prepare` (only when its inputs changed, or with --force) and select the compose files.
# Touches no running container.
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

HARBOR_YML="${ROOT_DIR}/harbor.yml"
PREPARE_STAMP="${ROOT_DIR}/.prepared"
# Created when prepare regenerated the configs; deploy.sh then recreates every container,
# because prepare replaces the bind-mounted config directories and rotates internal secrets.
RECREATE_FLAG="${ROOT_DIR}/.recreate"

force=0
for arg in "$@"; do
  case "${arg}" in
    --force) force=1 ;;
    *) die "usage: $0 [--force]" ;;
  esac
done

is_port() { [[ "${1:-}" =~ ^[0-9]+$ ]] && ((${1} >= 1 && ${1} <= 65535)); }

validate() {
  local errors=()
  [[ -n "${HARBOR_HOSTNAME:-}" && "${HARBOR_HOSTNAME}" != "harbor.example.com" ]] || errors+=("set HARBOR_HOSTNAME")
  [[ "${HARBOR_HOSTNAME:-}" =~ ^[A-Za-z0-9.-]+$ ]] || errors+=("HARBOR_HOSTNAME must be a plain hostname (no scheme, port or path)")
  [[ "${HARBOR_HOSTNAME:-}" != "127.0.0.1" ]] || errors+=("HARBOR_HOSTNAME cannot be 127.0.0.1")
  [[ -z "${EXTERNAL_URL:-}" || "${EXTERNAL_URL}" =~ ^https?://[A-Za-z0-9.-]+(:[0-9]+)?/?$ ]] \
    || errors+=("EXTERNAL_URL must look like https://host[:port]")

  case "${PROXY_MODE:-}" in
    traefik)
      [[ -n "${TRAEFIK_NETWORK:-}" ]] || errors+=("set TRAEFIK_NETWORK")
      [[ "${TRAEFIK_ALIAS:-}" =~ ^[A-Za-z0-9.-]+$ ]] || errors+=("set TRAEFIK_ALIAS")
      ;;
    standalone)
      is_port "${HTTP_PORT:-}" || errors+=("HTTP_PORT must be a port number")
      if [[ -n "${TLS_CERT:-}${TLS_KEY:-}" ]]; then
        is_port "${HTTPS_PORT:-}" || errors+=("HTTPS_PORT must be a port number")
        [[ "${TLS_CERT:-}" == /* && -r "${TLS_CERT:-}" ]] || errors+=("TLS_CERT must be an absolute path to a readable file")
        [[ "${TLS_KEY:-}" == /* && -r "${TLS_KEY:-}" ]] || errors+=("TLS_KEY must be an absolute path to a readable file")
      else
        warn "standalone without TLS_CERT/TLS_KEY: Harbor is served over plain HTTP"
      fi
      ;;
    *) errors+=("PROXY_MODE must be 'traefik' or 'standalone' (got '${PROXY_MODE:-}')") ;;
  esac

  if is_true "${ENABLE_METRICS:-0}"; then is_port "${METRICS_PORT:-}" || errors+=("METRICS_PORT must be a port number"); fi
  [[ "${MAX_JOB_WORKERS:-10}" =~ ^[0-9]+$ ]] || errors+=("MAX_JOB_WORKERS must be a number")
  [[ -z "${HARBOR_IMAGE_REGISTRY:-}" || "${HARBOR_IMAGE_REGISTRY}" == */ ]] || errors+=("HARBOR_IMAGE_REGISTRY needs a trailing slash")

  local key
  for key in HARBOR_ADMIN_PASSWORD HARBOR_DB_PASSWORD HARBOR_HTTP_PROXY HARBOR_HTTPS_PROXY HARBOR_NO_PROXY; do
    [[ ! "${!key:-}" =~ [\'[:space:]] ]] || errors+=("${key} must not contain quotes or whitespace")
  done
  if [[ -n "${HARBOR_ADMIN_PASSWORD:-}" ]]; then
    [[ ${#HARBOR_ADMIN_PASSWORD} -ge 8 && ${#HARBOR_ADMIN_PASSWORD} -le 128 \
       && "${HARBOR_ADMIN_PASSWORD}" =~ [A-Z] && "${HARBOR_ADMIN_PASSWORD}" =~ [a-z] && "${HARBOR_ADMIN_PASSWORD}" =~ [0-9] ]] \
      || errors+=("HARBOR_ADMIN_PASSWORD needs 8-128 characters with upper case, lower case and a digit")
  fi

  if ((${#errors[@]})); then
    printf '[harbor] .env: %s\n' "${errors[@]}" >&2
    die "fix ${ENV_FILE} and run again"
  fi
}

# PostgreSQL keeps the password it was initialised with, and Harbor applies the admin password
# only on the first start, so neither may be (re)generated once the database exists.
ensure_secrets() {
  local db_dir="${DATA_PATH}/database" db_exists=0
  [[ -d "${db_dir}" && -n "$(ls -A "${db_dir}" 2>/dev/null)" ]] && db_exists=1

  if [[ -z "${HARBOR_DB_PASSWORD:-}" ]]; then
    ((db_exists == 0)) || die "HARBOR_DB_PASSWORD is empty but ${db_dir} already has data — restore .env from your backup"
    env_set HARBOR_DB_PASSWORD "$(gen_secret)"
    log "secrets: generated HARBOR_DB_PASSWORD"
  fi
  if [[ -z "${HARBOR_ADMIN_PASSWORD:-}" ]]; then
    if ((db_exists)); then
      warn "HARBOR_ADMIN_PASSWORD is empty; the database already exists, so the current admin password stays as it is"
      # Ignored by Harbor at this point; derived rather than random so harbor.yml stays stable.
      HARBOR_ADMIN_PASSWORD="Unused0$(printf '%s' "${HARBOR_DB_PASSWORD}" | sha256sum | cut -c1-32)"
    else
      env_set HARBOR_ADMIN_PASSWORD "Hb$(openssl rand -hex 15)1"
      log "secrets: generated HARBOR_ADMIN_PASSWORD (user 'admin', see .env)"
    fi
  fi
}

render_harbor_yml() {
  local cfg_version tmp
  cfg_version="$(awk '/^_version:/ { print $2 }' "${ROOT_DIR}/upstream/harbor.yml.tmpl")"
  [[ -n "${cfg_version}" ]] || die "no _version in upstream/harbor.yml.tmpl"
  tmp="$(mktemp "${HARBOR_YML}.XXXXXX")"
  chmod 600 "${tmp}"
  {
    cat <<EOF
# Generated by scripts/setup.sh from .env — do not edit; changes are overwritten.
hostname: ${HARBOR_HOSTNAME}
http:
  port: ${HTTP_PORT:-80}
EOF
    if [[ "${PROXY_MODE}" == "standalone" && -n "${TLS_CERT:-}" ]]; then
      cat <<EOF
https:
  port: ${HTTPS_PORT:-443}
  certificate: ${TLS_CERT}
  private_key: ${TLS_KEY}
  strong_ssl_ciphers: true
EOF
    fi
    if [[ "${PROXY_MODE}" == "traefik" || -n "${EXTERNAL_URL:-}" ]]; then
      echo "external_url: $(public_url)"
    fi
    cat <<EOF
harbor_admin_password: '${HARBOR_ADMIN_PASSWORD}'
database:
  password: '${HARBOR_DB_PASSWORD}'
  max_idle_conns: 100
  max_open_conns: 900
  conn_max_lifetime: 5m
  conn_max_idle_time: 0
data_volume: ${DATA_PATH}
trivy:
  ignore_unfixed: false
  skip_update: $(is_true "${TRIVY_SKIP_UPDATE:-0}" && echo true || echo false)
  skip_java_db_update: $(is_true "${TRIVY_SKIP_UPDATE:-0}" && echo true || echo false)
  db_repository: ${TRIVY_DB_REPOSITORY:-ghcr.io/aquasecurity/trivy-db}
  java_db_repository: ${TRIVY_JAVA_DB_REPOSITORY:-ghcr.io/aquasecurity/trivy-java-db}
  offline_scan: false
  security_check: vuln
  insecure: false
  timeout: 5m0s
jobservice:
  max_job_workers: ${MAX_JOB_WORKERS:-10}
  max_job_duration_hours: 24
  job_loggers:
    - STD_OUTPUT
    - FILE
  logger_sweeper_duration: 1
notification:
  webhook_job_max_retry: 3
  webhook_job_http_client_timeout: 3
log:
  level: ${LOG_LEVEL:-info}
  local:
    rotate_count: ${LOG_ROTATE_COUNT:-50}
    rotate_size: ${LOG_ROTATE_SIZE:-200M}
    location: ${LOG_PATH}
_version: ${cfg_version}
proxy:
  http_proxy: ${HARBOR_HTTP_PROXY:-}
  https_proxy: ${HARBOR_HTTPS_PROXY:-}
  no_proxy: ${HARBOR_NO_PROXY:-}
  components:
    - core
    - jobservice
    - trivy
metric:
  enabled: $(is_true "${ENABLE_METRICS:-0}" && echo true || echo false)
  port: 9090
  path: /metrics
upload_purging:
  enabled: true
  age: 168h
  interval: 24h
  dryrun: false
cache:
  enabled: $(is_true "${ENABLE_CACHE:-0}" && echo true || echo false)
  expire_hours: 24
EOF
    if [[ -f "${ROOT_DIR}/config/harbor.extra.yml" ]]; then
      echo "# ---- config/harbor.extra.yml"
      cat "${ROOT_DIR}/config/harbor.extra.yml"
    fi
  } > "${tmp}"
  mv "${tmp}" "${HARBOR_YML}"
}

# Everything that influences prepare's output; certificates are copied by prepare, so a
# renewed certificate must trigger a new run as well.
prepare_inputs_hash() {
  {
    cat "${HARBOR_YML}"
    echo "${PREPARE_IMAGE} trivy=${ENABLE_TRIVY:-0}"
    if [[ "${PROXY_MODE}" == "standalone" && -n "${TLS_CERT:-}" ]]; then cat "${TLS_CERT}" "${TLS_KEY}"; fi
  } | sha256sum | cut -d' ' -f1
}

run_prepare() {
  local hash args=()
  hash="$(prepare_inputs_hash)"
  if ((force == 0)) && [[ -f "${ROOT_DIR}/docker-compose.yml" && -d "${ROOT_DIR}/common/config" \
                          && "$(cat "${PREPARE_STAMP}" 2>/dev/null)" == "${hash}" ]]; then
    log "prepare: harbor.yml unchanged, generated configuration is up to date"
    return
  fi

  command -v docker >/dev/null || die "docker not installed"
  mkdir -p "${DATA_PATH}" "${LOG_PATH}" "${ROOT_DIR}/common/config"
  # Inside ROOT_DIR (like upstream) rather than /tmp: the docker daemon must see the same path.
  PREPARE_INPUT="${ROOT_DIR}/input"
  rm -rf "${PREPARE_INPUT}"
  mkdir -m 700 "${PREPARE_INPUT}"
  trap 'rm -rf "${PREPARE_INPUT}"' EXIT
  cp "${HARBOR_YML}" "${PREPARE_INPUT}/harbor.yml"
  is_true "${ENABLE_TRIVY:-0}" && args+=(--with-trivy)

  log "prepare: running ${PREPARE_IMAGE}"
  # Same invocation as upstream/prepare; /hostfs lets it read TLS_CERT/TLS_KEY and LOG_DIR.
  docker run --rm --privileged \
    -v "${PREPARE_INPUT}:/input" \
    -v "${DATA_PATH}:/data" \
    -v "${ROOT_DIR}:/compose_location" \
    -v "${ROOT_DIR}/common/config:/config" \
    -v /:/hostfs/ \
    "${PREPARE_IMAGE}" prepare "${args[@]}"
  [[ -f "${ROOT_DIR}/docker-compose.yml" ]] || die "prepare did not generate docker-compose.yml"

  if [[ -n "${HARBOR_IMAGE_REGISTRY:-}" ]]; then
    sed -i -E "s#^([[:space:]]*image: )goharbor/#\1${HARBOR_IMAGE_REGISTRY}goharbor/#" "${ROOT_DIR}/docker-compose.yml"
  fi
  echo "${hash}" > "${PREPARE_STAMP}"
  touch "${RECREATE_FLAG}"
  log "prepare: generated docker-compose.yml and common/config/"
}

select_compose_files() {
  local files="docker-compose.yml:compose/common.yml"
  case "${PROXY_MODE}" in
    standalone)
      files+=":compose/standalone.yml"
      [[ -n "${TLS_CERT:-}" ]] && files+=":compose/standalone-tls.yml"
      ;;
    traefik)
      files+=":compose/traefik.yml"
      [[ -n "${TRAEFIK_CERTRESOLVER:-}" ]] && files+=":compose/traefik-certresolver.yml"
      [[ -n "${TRAEFIK_MIDDLEWARES:-}" ]] && files+=":compose/traefik-middlewares.yml"
      ;;
  esac
  is_true "${ENABLE_TRIVY:-0}" && files+=":compose/trivy.yml"
  is_true "${ENABLE_METRICS:-0}" && files+=":compose/metrics.yml"
  if [[ "${COMPOSE_FILE:-}" != "${files}" ]]; then
    env_set COMPOSE_FILE "${files}"
  fi
  log "compose files: ${files//:/ }"
}

main() {
  require_root setup
  command -v openssl >/dev/null || die "openssl not installed"
  load_env
  validate
  ensure_secrets
  render_harbor_yml
  run_prepare
  select_compose_files
  if docker compose version >/dev/null 2>&1; then
    compose config -q
    log "compose configuration valid"
  else
    warn "docker compose not found; skipped configuration check"
  fi
  log "setup done (Harbor ${HARBOR_VERSION}, ${PROXY_MODE}, $(public_url))"
}

main "$@"
