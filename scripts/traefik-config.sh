#!/usr/bin/env bash
# Print a Traefik file-provider route for Harbor, for a Traefik that does not read container
# labels (e.g. one running in Docker Swarm with only the swarm provider). Save the output in
# Traefik's dynamic configuration directory (providers.file.directory).
#   traefik:    routes to TRAEFIK_ALIAS on TRAEFIK_NETWORK (the overlay must be attachable)
#   standalone: routes to BIND_ADDRESS:HTTP_PORT (set BIND_ADDRESS to the host's private IP)
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
load_env

case "${PROXY_MODE:-}" in
  traefik) backend="http://${TRAEFIK_ALIAS:-harbor-proxy}:8080" ;;
  standalone)
    [[ -z "${TLS_CERT:-}" ]] || die "standalone mode with TLS_CERT already terminates TLS; route TCP to it or use PROXY_MODE=traefik"
    [[ "${BIND_ADDRESS:-0.0.0.0}" != "0.0.0.0" ]] || die "set BIND_ADDRESS to an address Traefik can reach"
    backend="http://${BIND_ADDRESS}:${HTTP_PORT:-80}"
    ;;
  *) die "PROXY_MODE must be 'traefik' or 'standalone'" ;;
esac

middlewares=""
if [[ -n "${TRAEFIK_MIDDLEWARES:-}" ]]; then
  middlewares=$'\n      middlewares:'
  IFS=',' read -ra mws <<<"${TRAEFIK_MIDDLEWARES}"
  for mw in "${mws[@]}"; do middlewares+=$'\n        - '"${mw}"; done
fi

cat <<EOF
# Harbor (${HARBOR_HOSTNAME}), generated by harbor/scripts/traefik-config.sh
http:
  routers:
    harbor:
      rule: Host(\`${HARBOR_HOSTNAME}\`)
      entryPoints:
        - ${TRAEFIK_ENTRYPOINT:-websecure}
      service: harbor
      tls: {${TRAEFIK_CERTRESOLVER:+certResolver: ${TRAEFIK_CERTRESOLVER}}}${middlewares}
  services:
    harbor:
      loadBalancer:
        passHostHeader: true
        servers:
          - url: ${backend}
EOF
